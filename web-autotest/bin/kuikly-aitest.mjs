#!/usr/bin/env node
/**
 * kuikly-aitest CLI
 * Usage: npx @tencent/kuikly-web-aitest init
 */
import { existsSync, mkdirSync, writeFileSync, copyFileSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const packageRoot = join(__dirname, '..');
const projectRoot = process.cwd();
const cmd = process.argv[2];
const modeArg = process.argv.find(a => a.startsWith('--mode=')) || (process.argv.indexOf('--mode') >= 0 ? `--mode=${process.argv[process.argv.indexOf('--mode') + 1]}` : null);
const mode = modeArg ? modeArg.split('=')[1] : 'framework';

if (cmd === 'init') {
  if (mode === 'business') {
    initBusiness();
  } else {
    init();
  }
} else {
  console.log('Usage: npx @tencent/kuikly-web-aitest init');
  process.exit(1);
}

function ensureDir(dir) {
  if (!existsSync(dir)) {
    mkdirSync(dir, { recursive: true });
    console.log(`  created: ${dir}`);
  }
}

function copyIfAbsent(src, dest) {
  if (existsSync(dest)) {
    console.log(`  skip (exists): ${dest}`);
    return;
  }
  copyFileSync(src, dest);
  console.log(`  copied: ${dest}`);
}

function init() {
  const autotestDir = join(projectRoot, 'web-autotest');
  console.log('\nInitializing kuikly-aitest scaffold...\n');

  // Directory structure
  ensureDir(autotestDir);
  ['tests', 'tests/static', 'tests/functional', 'tests/visual', 'reports', 'fonts', 'project-rules'].forEach(
    (d) => ensureDir(join(autotestDir, d))
  );

  // Config file (copy template, consumer modifies)
  copyIfAbsent(
    join(packageRoot, 'kuikly.autotest.config.cjs'),
    join(autotestDir, 'kuikly.autotest.config.cjs')
  );

  // playwright.config.js
  const pwConfigDest = join(autotestDir, 'playwright.config.js');
  if (!existsSync(pwConfigDest)) {
    writeFileSync(pwConfigDest, `// Generated by: npx @tencent/kuikly-web-aitest init
const { createPlaywrightConfig } = require('@tencent/kuikly-web-aitest/config/playwright-factory');
module.exports = createPlaywrightConfig({ testDir: './tests' });
`);
    console.log(`  created: ${pwConfigDest}`);
  } else {
    console.log(`  skip (exists): ${pwConfigDest}`);
  }

  // Claude Code integration
  const claudeCommandsDir = join(projectRoot, '.claude', 'commands');
  ensureDir(claudeCommandsDir);
  const commandStub = join(claudeCommandsDir, 'kuikly-web-autotest.md');
  if (!existsSync(commandStub)) {
    writeFileSync(commandStub, '@../node_modules/@tencent/kuikly-web-aitest/SKILL.md\n');
    console.log(`  created: ${commandStub}`);
  } else {
    console.log(`  skip (exists): ${commandStub}`);
  }

  // web-autotest/SKILL.md stub
  const skillStub = join(autotestDir, 'SKILL.md');
  if (!existsSync(skillStub)) {
    writeFileSync(skillStub, '@../node_modules/@tencent/kuikly-web-aitest/SKILL.md\n');
    console.log(`  created: ${skillStub}`);
  } else {
    console.log(`  skip (exists): ${skillStub}`);
  }

  console.log('\nDone! Next steps:');
  console.log('  1. Edit web-autotest/kuikly.autotest.config.cjs for your project paths');
  console.log('  2. Run: npx playwright install chromium');
}

function initBusiness() {
  const autotestDir = join(projectRoot, 'web-autotest');
  console.log('\nInitializing kuikly-aitest scaffold (business mode)...\n');

  // Base directories
  ensureDir(autotestDir);
  ['tests', 'reports', 'fonts', 'project-rules'].forEach(
    (d) => ensureDir(join(autotestDir, d))
  );

  // Example business directories
  const exampleBiz = 'example_biz';
  ensureDir(join(autotestDir, 'tests', exampleBiz));
  ensureDir(join(autotestDir, 'tests', exampleBiz, 'visual'));
  ensureDir(join(autotestDir, 'tests', exampleBiz, 'functional'));

  // Business mode config template
  const configDest = join(autotestDir, 'kuikly.autotest.config.cjs');
  if (!existsSync(configDest)) {
    writeFileSync(configDest, `/**
 * Business-mode configuration for kuikly web autotest.
 * Generated by: npx @tencent/kuikly-web-aitest init --mode business
 */
module.exports = {
  mode: 'business',

  businesses: [
    {
      name: 'example_biz',
      bundleName: 'example_biz',
      displayName: 'Example Business',
      urlPattern: '/example_biz/index.html',
      // Source directory for AI spec generation (relative to project root)
      sourceDir: 'src/example_biz',
      // Optional: build command for this business
      // buildCommand: './gradlew :h5App:example_biz:publishLocalJSBundle',
    },
  ],

  server: {
    baseURL: 'http://localhost:8017',
    skipBuiltinServer: true,
    // startCommand: 'node static_server/serve/index.js',
    port: 8017,
  },

  testTypes: ['visual', 'functional'],

  // Framework-mode fields (not used in business mode)
  webTestRoot: null,
  sourceRoots: [],
  build: { gradleBuildArgs: null },
  coverage: null,
};
`);
    console.log(`  created: ${configDest}`);
  } else {
    console.log(`  skip (exists): ${configDest}`);
  }

  // playwright.config.js
  const pwConfigDest = join(autotestDir, 'playwright.config.js');
  if (!existsSync(pwConfigDest)) {
    writeFileSync(pwConfigDest, `// Generated by: npx @tencent/kuikly-web-aitest init --mode business
const { createPlaywrightConfig } = require('@tencent/kuikly-web-aitest/config/playwright-factory');
module.exports = createPlaywrightConfig({ testDir: './tests' });
`);
    console.log(`  created: ${pwConfigDest}`);
  } else {
    console.log(`  skip (exists): ${pwConfigDest}`);
  }

  // Example spec
  const exampleSpec = join(autotestDir, 'tests', exampleBiz, 'visual', `${exampleBiz}.visual.spec.ts`);
  if (!existsSync(exampleSpec)) {
    writeFileSync(exampleSpec, `import { test, expect } from '@tencent/kuikly-web-aitest';

test.describe('example_biz visual regression', () => {
  test('homepage renders correctly', async ({ kuiklyPage }) => {
    await kuiklyPage.goto({ bundle: 'example_biz' });
    await kuiklyPage.waitForRenderComplete();
    await expect(kuiklyPage.page).toHaveScreenshot('homepage.png');
  });
});
`);
    console.log(`  created: ${exampleSpec}`);
  } else {
    console.log(`  skip (exists): ${exampleSpec}`);
  }

  // Claude Code integration (same as framework mode)
  const claudeCommandsDir = join(projectRoot, '.claude', 'commands');
  ensureDir(claudeCommandsDir);
  const commandStub = join(claudeCommandsDir, 'kuikly-web-autotest.md');
  if (!existsSync(commandStub)) {
    writeFileSync(commandStub, '@../node_modules/@tencent/kuikly-web-aitest/SKILL.md\n');
    console.log(`  created: ${commandStub}`);
  } else {
    console.log(`  skip (exists): ${commandStub}`);
  }

  // web-autotest/SKILL.md stub
  const skillStub = join(autotestDir, 'SKILL.md');
  if (!existsSync(skillStub)) {
    writeFileSync(skillStub, '@../node_modules/@tencent/kuikly-web-aitest/SKILL.md\n');
    console.log(`  created: ${skillStub}`);
  } else {
    console.log(`  skip (exists): ${skillStub}`);
  }

  console.log('\nDone! Next steps:');
  console.log('  1. Edit web-autotest/kuikly.autotest.config.cjs — add your businesses');
  console.log('  2. Start your local server (e.g., npm run serve)');
  console.log('  3. Run: npx playwright install chromium');
  console.log('  4. Write a spec and run: node node_modules/@tencent/kuikly-web-aitest/scripts/kuikly-test.mjs --skip-build --biz example_biz');
}
